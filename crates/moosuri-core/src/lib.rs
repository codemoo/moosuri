//! Public API contracts. No database connections, authentication secrets or IO.
use serde::{Deserialize, Serialize};
use ts_rs::TS;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum Role {
    Admin,
    Member,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
pub struct AccountSummary {
    pub id: String,
    pub name: String,
    pub email: String,
    pub role: Role,
    pub must_change_password: bool,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct SessionView {
    pub user: AccountSummary,
    pub password_change_required: bool,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct SystemStatus {
    pub version: String,
    pub initialized: bool,
    pub stage: String,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct ThreadSummary {
    pub id: String,
    pub title: String,
    #[ts(type = "number")]
    pub created_at: i64,
    #[ts(type = "number")]
    pub updated_at: i64,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct ThreadsResponse {
    pub threads: Vec<ThreadSummary>,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct UsersResponse {
    pub users: Vec<AccountSummary>,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct ApiError {
    pub code: String,
}

/// Generated for the React client; request secrets deliberately have no Debug DTO.
pub fn typescript_contract() -> String {
    let declarations = [
        Role::decl(),
        AccountSummary::decl(),
        SessionView::decl(),
        SystemStatus::decl(),
        ThreadSummary::decl(),
        ThreadsResponse::decl(),
        UsersResponse::decl(),
        ApiError::decl(),
    ];
    let mut result = String::from("// Generated by moosuri export-types. Do not edit.\n");
    for declaration in declarations {
        result.push_str("export ");
        result.push_str(&declaration);
        result.push('\n');
    }
    result
}
